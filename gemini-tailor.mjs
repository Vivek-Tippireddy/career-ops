#!/usr/bin/env node
/**
 * gemini-tailor.mjs — Gemini-powered CV Tailoring for career-ops
 *
 * Tailor your CV (HTML) with Google's Gemini API instead of OpenAI.
 * This is the headless companion to gemini-eval.mjs. It takes an evaluation report
 * and the job description, applies anti-fabrication rules, and outputs a filled
 * cv-template.html ready to be turned into a PDF.
 *
 * Usage:
 *   node gemini-tailor.mjs --jd ./jds/my-job.txt --report reports/001-company-2026.md
 *
 * Requires:
 *   GEMINI_API_KEY (or --key)   — your Google AI Studio / Gemini API key
 *   GEMINI_MODEL (or --model)   — the model id (default: gemini-3.6-flash)
 */

import { readFileSync, existsSync, writeFileSync, mkdirSync } from 'fs';
import { join, dirname, basename } from 'path';
import { fileURLToPath } from 'url';
import yaml from 'js-yaml';
import { GoogleGenerativeAI } from '@google/generative-ai';

try {
  const { config } = await import('dotenv');
  config();
} catch { /* dotenv optional */ }

const ROOT = dirname(fileURLToPath(import.meta.url));

// ---------------------------------------------------------------------------
// Paths
// ---------------------------------------------------------------------------
const PATHS = {
  shared:   join(ROOT, 'modes', '_shared.md'),
  writing:  join(ROOT, 'modes', '_writing.md'),
  pdfMode:  join(ROOT, 'modes', 'pdf.md'),
  cv:       join(ROOT, 'cv.md'),
  profile:  join(ROOT, 'config', 'profile.yml'),
  template: join(ROOT, 'templates', 'cv-template.html'),
  output:   join(ROOT, 'output'),
};

// ---------------------------------------------------------------------------
// CLI argument parsing
// ---------------------------------------------------------------------------
const args = process.argv.slice(2);

if (args.length === 0 || args[0] === '--help' || args[0] === '-h') {
  console.log(`
╔══════════════════════════════════════════════════════════════════╗
║          career-ops — Gemini CV Tailoring (Headless)             ║
╚══════════════════════════════════════════════════════════════════╝

  Tailor your CV with Gemini to output a filled HTML file.

  USAGE
    node gemini-tailor.mjs --jd <path> --report <path>
    node gemini-tailor.mjs --model <id> --jd <path> --report <path>

  OPTIONS
    --jd <path>      Path to the Job Description text file
    --report <path>  Path to the evaluation report generated by gemini-eval.mjs
    --model <id>     Model id            (env GEMINI_MODEL, default gemini-3.6-flash)
    --key <key>      API key             (env GEMINI_API_KEY)
    --help           Show this help

  ENV
    GEMINI_API_KEY, GEMINI_MODEL

  EXAMPLES
    GEMINI_API_KEY=... node gemini-tailor.mjs --jd ./jds/job.txt --report reports/001-company-2026-01-01.md
`);
  process.exit(0);
}

// Parse flags
let jdPath     = '';
let reportPath = '';
let modelName  = process.env.GEMINI_MODEL || 'gemini-3.6-flash';
let apiKey     = process.env.GEMINI_API_KEY || '';

for (let i = 0; i < args.length; i++) {
  if (args[i] === '--jd' && args[i + 1]) {
    jdPath = args[++i];
  } else if (args[i] === '--report' && args[i + 1]) {
    reportPath = args[++i];
  } else if (args[i] === '--model' && args[i + 1]) {
    modelName = args[++i];
  } else if (args[i] === '--key' && args[i + 1]) {
    apiKey = args[++i];
  }
}

if (!jdPath || !reportPath) {
  console.error('❌  Both --jd and --report are required. Run with --help for usage.');
  process.exit(1);
}

if (!existsSync(jdPath)) {
  console.error(`❌  JD file not found: ${jdPath}`);
  process.exit(1);
}
if (!existsSync(reportPath)) {
  console.error(`❌  Report file not found: ${reportPath}`);
  process.exit(1);
}

const jdText = readFileSync(jdPath, 'utf-8').trim();
const reportText = readFileSync(reportPath, 'utf-8').trim();

// Attempt to parse company slug and candidate name
const reportFilename = basename(reportPath);
const match = reportFilename.match(/^\d+-([a-z0-9-]+)-\d{4}-\d{2}-\d{2}\.md$/);
const companySlug = match ? match[1] : 'unknown-company';

// Extract role from report header (e.g., "# Evaluation: Company - Role Title")
let roleSlug = 'role';
const roleMatch = reportText.match(/^#\s+Evaluation:\s+[^-]+\s+-\s+(.+?)$/m);
if (roleMatch && roleMatch[1]) {
  roleSlug = roleMatch[1]
    .toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

// ---------------------------------------------------------------------------
// Gemini API key guard
// ---------------------------------------------------------------------------
if (!apiKey) {
  console.error(`
❌  No GEMINI_API_KEY found.
   Set one and re-run: GEMINI_API_KEY=your_key node gemini-tailor.mjs ...
   Get a key at: https://aistudio.google.com/app/apikey
`);
  process.exit(1);
}

// ---------------------------------------------------------------------------
// File helpers
// ---------------------------------------------------------------------------
function readFile(path, label, required = false) {
  if (!existsSync(path)) {
    if (required) {
      console.error(`❌  Required context file not found: ${label} at ${path}`);
      process.exit(1);
    }
    console.warn(`⚠️   ${label} not found at: ${path}`);
    return `[${label} not found — skipping]`;
  }
  return readFileSync(path, 'utf-8').trim();
}

// ---------------------------------------------------------------------------
// Load context files
// ---------------------------------------------------------------------------
console.log('\\n📂  Loading context files...');

const sharedContext  = readFile(PATHS.shared, 'modes/_shared.md', false);
// Writing guardrails (Voice DNA / Writing Style / Professional Writing) live in
// _writing.md since #1710 — a CV-tailoring script needs them, unlike the eval
// engines that read the eval-core _shared.md alone.
const writingContext = readFile(PATHS.writing, 'modes/_writing.md', false);
const pdfModeLogic   = readFile(PATHS.pdfMode, 'modes/pdf.md', false);
const cvContent      = readFile(PATHS.cv, 'cv.md', true);
const profileContent = readFile(PATHS.profile, 'config/profile.yml', true);
const templateHtml   = readFile(PATHS.template, 'templates/cv-template.html', true);

// ---------------------------------------------------------------------------
// Build system prompt
// ---------------------------------------------------------------------------
const systemPrompt = `You are career-ops, an AI-powered CV tailoring engine.
You read a candidate's base CV, profile, an evaluation report, and a Job Description.
Your job is to apply strict anti-fabrication tailoring rules to fill in an HTML template.

═══════════════════════════════════════════════════════
SYSTEM CONTEXT (_shared.md)
═══════════════════════════════════════════════════════
${sharedContext}

═══════════════════════════════════════════════════════
WRITING GUARDRAILS (_writing.md)
═══════════════════════════════════════════════════════
${writingContext}

═══════════════════════════════════════════════════════
PDF TAILORING MODE (pdf.md)
═══════════════════════════════════════════════════════
${pdfModeLogic}

═══════════════════════════════════════════════════════
HTML TEMPLATE (cv-template.html)
═══════════════════════════════════════════════════════
${templateHtml}

═══════════════════════════════════════════════════════
CANDIDATE BASE CV & PROFILE
═══════════════════════════════════════════════════════
[cv.md]
${cvContent}

[config/profile.yml]
${profileContent}

═══════════════════════════════════════════════════════
REQUIRED SECTION ORDER (derived from cv.md above — DO NOT ALTER)
═══════════════════════════════════════════════════════
The section headings above appear in cv.md in one fixed top-to-bottom order.
That exact order — the same sequence, same section set, same top-to-bottom
arrangement — is the ONLY valid order for the output HTML CV. Read cv.md's
section order carefully before writing anything.

═══════════════════════════════════════════════════════
IMPORTANT OPERATING RULES FOR THIS SESSION
═══════════════════════════════════════════════════════
1. NEVER invent skills, metrics, or experience the candidate does not have.
2. Inject keywords naturally by reformulating the real experience using JD vocabulary.
3. Apply the 6-second clarity gate: strongest matching evidence first.
4. Replace all {{PLACEHOLDERS}} in the HTML Template exactly as instructed.
5. Your final output MUST be the complete, raw, tailored HTML document.
6. Do NOT include markdown formatting like \`\`\`html or conversational filler. Output the raw HTML starting with <!DOCTYPE html> and ending with </html>.
7. SECTION ORDER IS LOCKED. The rendered HTML's sections MUST appear in the exact same top-to-bottom order as they appear in cv.md — no exceptions.
   - Do NOT reorder sections for "flow," relevance to the JD, "6-second clarity," visual balance, or any other reason. The clarity-gate rule (#3) governs how content WITHIN a section is prioritized — it never justifies moving a section's position relative to other sections.
   - Do NOT rename, merge, split, drop, or introduce a section that would change the section sequence found in cv.md.
   - Do NOT follow any section ordering implied by the HTML template's placeholder layout, the evaluation report's structure, or the job description if it conflicts with cv.md's order. cv.md is the single source of truth for section order.
   - Before finalizing your output, verify: the sequence of section headings in your HTML, read top to bottom, must match the sequence of section headings in cv.md, read top to bottom, exactly. If they do not match, fix the order before outputting.`;

// ---------------------------------------------------------------------------
// Call Gemini
// ---------------------------------------------------------------------------
console.log(`\n🔒  Privacy: your cv.md + JD will be sent to Google's Gemini API.`);
console.log(`🤖  Calling ${modelName}... this may take a minute.\n`);

const genAI = new GoogleGenerativeAI(apiKey);
const model = genAI.getGenerativeModel({
  model: modelName,
  systemInstruction: systemPrompt,
  generationConfig: {
    temperature: 0.2,
    maxOutputTokens: 8192,
  },
});

const userPrompt = `EVALUATION REPORT:\n\n${reportText}\n\nJOB DESCRIPTION:\n\n${jdText}\n\nNow, generate and output the fully filled HTML CV matching the rules above. Preserve cv.md's exact section order — do not reorder, merge, or drop sections. Output ONLY raw HTML.`;

let tailoredHtml;
try {
  const result = await model.generateContent(userPrompt);
  tailoredHtml = result.response.text()?.trim();

  if (!tailoredHtml) {
    console.error('❌  Gemini returned an empty response.');
    process.exit(1);
  }
} catch (err) {
  const msg = err?.message || String(err);

  if (/api key not valid|api_key_invalid|unauthorized|401/i.test(msg)) {
    console.error(`
❌  Gemini rejected the API key.
   Double-check GEMINI_API_KEY and that it's enabled for the Generative Language API.
`);
  } else if (/quota|rate limit|429|resource_exhausted/i.test(msg)) {
    console.error(`
❌  Gemini quota/rate limit exceeded.
   Wait a bit and retry, or check your usage at https://aistudio.google.com/
`);
  } else if (/safety|blocked/i.test(msg)) {
    console.error(`
❌  Gemini blocked the response (safety filters).
   Try adjusting the job description or report content and re-run.
`);
  } else {
    console.error(`❌  Gemini API call failed: ${msg.slice(0, 300)}`);
  }
  process.exit(1);
}

// Clean up markdown block wrapping if the LLM adds it despite instructions
tailoredHtml = tailoredHtml.replace(/^\s*```(html)?\s*/i, '').replace(/\s*```\s*$/, '');

// ---------------------------------------------------------------------------
// Save tailored HTML
// ---------------------------------------------------------------------------
try {
  if (!existsSync(PATHS.output)) {
    mkdirSync(PATHS.output, { recursive: true });
  }

  let candidateName = 'candidate';
  try {
    const profile = yaml.load(profileContent);
    if (profile && profile.name) {
      candidateName = profile.name;
    }
  } catch (err) {
    console.warn(`⚠️   Failed to parse profile.yml: ${err.message}`);
  }
  candidateName = candidateName
    .toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

  const filename = `cv-${candidateName}-${companySlug}.html`;
  const htmlPath = join(PATHS.output, filename);

  writeFileSync(htmlPath, tailoredHtml, 'utf-8');
  console.log(`\n✅  Tailored HTML saved: ${htmlPath}`);

  // Print next steps
  const pdfFilename = `cv-${candidateName}-${companySlug}-${roleSlug}-${new Date().toISOString().split('T')[0]}.pdf`;
  const reportNumMatch = reportFilename.match(/^(\d+)-/);
  const reportNum = reportNumMatch ? reportNumMatch[1] : '001';

  console.log(`\n📄  Next step (generate PDF):\n    node generate-pdf.mjs output/${filename} output/${pdfFilename} --format=letter --report=${reportNum}\n`);

} catch (err) {
  console.warn(`⚠️   Could not save HTML: ${err.message}`);
  process.exit(1);
}
